export type SeedState = ReturnType<typeof createSeedState>;

export function computePulse(state: SeedState): ChapterPulse {
  const active = state.projects.filter((p) => !p.archived);
  return {
    attentionCount: state.workItems.filter((w) => w.bucket === "now" || w.bucket === "overdue").length,
    projectsAtRisk: active.filter((p) => p.health === "at_risk" || p.health === "blocked").length,
    approvalsWaiting: state.approvals.filter((a) => a.status === "pending").length,
    nextMeeting: state.meetings[0]?.title ?? "—",
    activity7d: [4, 6, 5, 8, 7, 9, 6],
    portfolioHealth: active.map((p) => p.progressPercent),
  };
}
